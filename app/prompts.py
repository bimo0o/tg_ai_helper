def instruction_messages(mode: str, max_output_tokens: int | None = None) -> list[dict[str, str]]:
    system = SYSTEM_PROMPTS[mode]
    if max_output_tokens is not None:
        if type(max_output_tokens) is not int or not 1 <= max_output_tokens <= 8192:
            raise ValueError("Invalid output budget.")
        system += f"\n\nБюджет ответа: {max_output_tokens} выходных токенов. "
        if mode == "translate":
            system += (
                "Сохраняй точность перевода: не заменяй его пересказом и не пропускай "
                "части оригинала ради краткости. Не добавляй введений и комментариев."
            )
        else:
            words = max(8, max_output_tokens // 6)
            system += (
                f"Ориентир для русского ответа — до {words} слов с запасом под ссылки "
                "и оформление; это приблизительная оценка, не точное число токенов. "
                "Сначала распредели объём между всеми частями вопроса. В начале дай "
                "законченный краткий ответ или план, затем только важные пояснения. "
                "Не трать весь бюджет на введение или первую часть. Объединяй повторы, "
                "не переписывай вопрос и определения. Заверши все начатые предложения "
                "и списки до лимита. Если подробности не помещаются, дай полный краткий "
                "ответ по всем аспектам и предложи отдельно раскрыть нужный пункт. "
                "Не начинай большой раздел, для которого не осталось места. "
                "Примеры программ оформляй fenced-блоками Markdown: открывающая строка "
                "```python (или нужный язык), затем код с настоящими переносами строк "
                "и отступами, затем отдельная закрывающая строка ```. Не склеивай "
                "инструкции Python в одну строку ради краткости: сокращай объяснения. "
                "Внутри кода не экранируй звёздочки и подчёркивания как Markdown, "
                "не заменяй пробелы HTML-сущностями и не превращай строковые URL "
                "в Markdown-ссылки. При буквальном повторении текста, которое не "
                "помещается в бюджет, честно объясни ограничение; не выдавай код, "
                "генерирующий текст, за выполненное повторение."
            )
    messages = [{"role": "system", "content": system}]
    for user, assistant in FEW_SHOT.get(mode, ()):
        messages.extend(
            [{"role": "user", "content": user}, {"role": "assistant", "content": assistant}]
        )
    return messages


def profile_messages(profile: dict[str, str]) -> list[dict[str, str]]:
    if not profile:
        return []
    return [
        {
            "role": "user",
            "content": "Мой музыкальный профиль (справочные данные):\n"
            + json.dumps(profile, ensure_ascii=False, sort_keys=True),
        }
    ]
