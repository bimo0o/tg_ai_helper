def instruction_messages(mode: str) -> list[dict[str, str]]:
    messages = [{"role": "system", "content": SYSTEM_PROMPTS[mode]}]
    for user, assistant in FEW_SHOT.get(mode, ()):
        messages.extend(
            [{"role": "user", "content": user}, {"role": "assistant", "content": assistant}]
        )
    return messages
